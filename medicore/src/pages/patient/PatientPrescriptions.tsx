export default function PatientPrescriptions() {
  const { user } = useAuth();
  const prescriptions = useMemo(
    () => getAll<Prescription>(STORAGE_KEYS.PRESCRIPTIONS).filter((r) => r.patientId === user?.id),
    [user?.id]
  );

  return (
    <div className="p-6 max-w-4xl mx-auto">
      <div className="page-header">
        <h1 className="page-title">Prescriptions</h1>
        <p className="page-subtitle">{prescriptions.length} prescriptions</p>
      </div>

      <div className="mb-6 p-4 bg-amber-50 dark:bg-amber-900/20 border border-amber-200 dark:border-amber-700 rounded-2xl flex items-start gap-3">
        <AlertTriangle size={16} className="text-amber-600 shrink-0 mt-0.5" />
        <p className="text-xs text-amber-700 dark:text-amber-400">
          <strong>Sample Data â€” Not Valid Medical Documents.</strong> All prescriptions are fictional demo data for the college project only.
        </p>
      </div>

      {prescriptions.length === 0 ? (
        <EmptyState
          icon={Pill}
          title="No prescriptions"
          description="Prescriptions from your completed visits will appear here."
        />
      ) : (
        <div className="space-y-5">
          {prescriptions.map((rx, i) => (
            <motion.div
              key={rx.id}
              className="card p-6"
              initial={{ opacity: 0, y: 10 }}
              animate={{ opacity: 1, y: 0 }}
              transition={{ delay: i * 0.08 }}
            >
              <div className="flex items-start justify-between gap-3 mb-5">
                <div>
                  <h3 className="font-semibold text-slate-900 dark:text-white font-heading">
                    {rx.diagnosis}
                  </h3>
                  <div className="flex items-center gap-3 mt-1 text-sm text-slate-500 dark:text-slate-400">
                    <span className="flex items-center gap-1"><User size={13} />{rx.doctorName}</span>
                    <span className="flex items-center gap-1"><Calendar size={13} />{format(new Date(rx.issueDate), 'PPP')}</span>
                  </div>
                </div>
                <div className="flex gap-2">
                  <button
                    onClick={() => printPrescription(rx)}
                    className="btn-secondary text-xs py-1.5 px-3"
                    title="Print prescription"
                  >
                    <Printer size={13} /> Print
                  </button>
                </div>
              </div>

              <div className="overflow-x-auto rounded-xl border border-slate-100 dark:border-slate-700">
                <table className="w-full text-sm">
                  <thead className="bg-slate-50 dark:bg-slate-700/50">
                    <tr>
                      {['Medication', 'Dosage', 'Frequency', 'Duration', 'Instructions'].map((h) => (
                        <th key={h} className="text-left px-4 py-2.5 text-xs font-semibold text-slate-600 dark:text-slate-400">
                          {h}
                        </th>
                      ))}
                    </tr>
                  </thead>
                  <tbody>
                    {rx.medications.map((med, j) => (
                      <tr key={j} className="border-t border-slate-100 dark:border-slate-700">
                        <td className="px-4 py-2.5 font-medium text-slate-900 dark:text-white">{med.name}</td>
                        <td className="px-4 py-2.5 text-slate-600 dark:text-slate-400">{med.dosage}</td>
                        <td className="px-4 py-2.5 text-slate-600 dark:text-slate-400">{med.frequency}</td>
                        <td className="px-4 py-2.5 text-slate-600 dark:text-slate-400">{med.duration}</td>
                        <td className="px-4 py-2.5 text-slate-500 dark:text-slate-500 text-xs">{med.instructions ?? 'â€”'}</td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>

              {rx.instructions && (
                <div className="mt-4 p-3 rounded-xl bg-blue-50 dark:bg-blue-900/20">
                  <p className="text-xs text-blue-600 dark:text-blue-400 mb-1 font-semibold">Instructions</p>
                  <p className="text-sm text-slate-700 dark:text-slate-300">{rx.instructions}</p>
                </div>
              )}

              {rx.validUntil && (
                <p className="text-xs text-slate-400 mt-3">Valid until: {format(new Date(rx.validUntil), 'PPP')}</p>
              )}
            </motion.div>
          ))}
        </div>
      )}
    </div>
  );
}

